create or replace function public.warn_member(p_user uuid, p_reason text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare v_reason text := btrim(coalesce(p_reason, '')); t public.profiles%rowtype;
begin
  if auth.uid() is null or not public.is_staff() then raise exception 'non autorisé'; end if;
  if p_user = auth.uid() then raise exception 'tu ne peux pas t''avertir toi-même'; end if;
  if char_length(v_reason) < 3 then raise exception 'motif obligatoire (3 caractères minimum)'; end if;
  if char_length(v_reason) > 300 then raise exception 'motif trop long (300 caractères maximum)'; end if;
  select * into t from public.profiles where id = p_user;
  if not found then raise exception 'membre introuvable'; end if;
  if not public.is_admin() and (t.is_admin or t.is_controller) then raise exception 'seul le développeur peut avertir un membre du staff'; end if;
  perform public.modlog('warning', p_user, null, v_reason);
  insert into public.notifications (user_id, title, body, url, tag)
  values (p_user, '⚠️ Avertissement', 'Un modérateur t''adresse un avertissement. Motif : ' || v_reason || '. En cas de récidive, ton compte pourra être suspendu.', './#profil', 'warn-' || extract(epoch from now())::bigint);
end $$;
revoke all on function public.warn_member(uuid, text) from public, anon;
grant execute on function public.warn_member(uuid, text) to authenticated;

-- dossier d'un membre : avertissements et sanctions des 6 derniers mois, palier conseillé
create or replace function public.member_record(p_user uuid)
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare w int; t24 int; t7 int; tot int; next text;
begin
  if auth.uid() is null or not public.is_staff() then raise exception 'non autorisé'; end if;
  select count(*) into w from public.moderation_log where target_user = p_user and action = 'warning' and at > now() - interval '180 days';
  select count(*) filter (where ends_at - starts_at >= interval '1 day' and ends_at - starts_at < interval '7 days'),
         count(*) filter (where ends_at - starts_at >= interval '7 days'),
         count(*)
    into t24, t7, tot
    from public.moderation_timeouts where user_id = p_user and starts_at > now() - interval '180 days'
     and coalesce(lift_reason, '') <> 'Remplacé par une nouvelle sanction';
  next := case when w = 0 and tot = 0 then 'warning'
               when t24 = 0 and t7 = 0 then '1440'
               else '10080' end;
  return jsonb_build_object(
    'warnings', w, 'timeouts', tot, 'next', next,
    'history', coalesce((select jsonb_agg(jsonb_build_object('at', at, 'action', action, 'details', details) order by at desc)
                          from (select at, action, details from public.moderation_log
                                 where target_user = p_user and action in ('warning','timeout','lift_timeout','delete_post','delete_comment','delete_message','remove_member')
                                 order by at desc limit 15) x), '[]'::jsonb));
end $$;
revoke all on function public.member_record(uuid) from public, anon;
grant execute on function public.member_record(uuid) to authenticated;

