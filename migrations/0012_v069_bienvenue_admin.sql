create table if not exists public.announcements (
  id         bigint generated by default as identity primary key,
  title      text not null check (char_length(btrim(title)) between 3 and 80),
  body       text check (body is null or char_length(body) <= 500),
  level      text not null default 'info' check (level in ('info', 'nouveau', 'important', 'maintenance')),
  starts_at  timestamptz not null default now(),
  ends_at    timestamptz not null default now() + interval '7 days',
  push       boolean not null default false,
  created_by uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint announcements_span check (ends_at > starts_at)
);
alter table public.announcements enable row level security;
drop policy if exists announcements_select on public.announcements;
create policy announcements_select on public.announcements for select to anon, authenticated
  using ((now() >= starts_at and now() < ends_at) or public.is_admin());
drop policy if exists announcements_insert on public.announcements;
create policy announcements_insert on public.announcements for insert to authenticated with check (public.is_admin());
drop policy if exists announcements_update on public.announcements;
create policy announcements_update on public.announcements for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists announcements_delete on public.announcements;
create policy announcements_delete on public.announcements for delete to authenticated using (public.is_admin());
drop trigger if exists announcements_notify on public.announcements;
create trigger announcements_notify after insert on public.announcements
  for each row when (new.push and new.starts_at <= now()) execute function public.notify_new();

