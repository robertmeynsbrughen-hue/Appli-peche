create or replace function public.log_client_error(p_message text, p_source text, p_line int, p_version text, p_screen text, p_agent text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare msg text := left(btrim(coalesce(p_message, '')), 300);
begin
  if msg = '' then return; end if;
  -- limites : 30 par heure et par compte, 500 par heure au total, pas de doublon sous 10 min
  if (select count(*) from public.client_errors where at > now() - interval '1 hour') >= 500 then return; end if;
  if auth.uid() is not null and (select count(*) from public.client_errors where user_id = auth.uid() and at > now() - interval '1 hour') >= 30 then return; end if;
  if exists (select 1 from public.client_errors where message = msg and user_id is not distinct from auth.uid() and at > now() - interval '10 minutes') then return; end if;
  insert into public.client_errors (user_id, message, source, line, version, screen, agent)
  values (auth.uid(), msg, left(p_source, 120), p_line, left(p_version, 20), left(p_screen, 40), left(p_agent, 120));
end $$;
revoke all on function public.log_client_error(text, text, int, text, text, text) from public;
grant execute on function public.log_client_error(text, text, int, text, text, text) to anon, authenticated;

create or replace function public.app_health()
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare out jsonb; r record; push_ok int := 0; push_bad int := 0; calls int := 0; bad_calls jsonb := '[]'::jsonb; c jsonb; x jsonb;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'non autorisé'; end if;
  for r in select status_code, content, created from net._http_response where created > now() - interval '24 hours' order by id desc loop
    calls := calls + 1;
    if r.status_code is distinct from 200 then
      if jsonb_array_length(bad_calls) < 8 then bad_calls := bad_calls || jsonb_build_object('at', r.created, 'status', r.status_code, 'msg', left(coalesce(r.content, ''), 140)); end if;
    else
      begin
        c := r.content::jsonb;
        if jsonb_typeof(c->'results') = 'array' then
          for x in select * from jsonb_array_elements(c->'results') loop
            if x::text in ('201', '200', '202') then push_ok := push_ok + 1; else push_bad := push_bad + 1; end if;
          end loop;
        end if;
      exception when others then null;
      end;
    end if;
  end loop;
  out := jsonb_build_object(
    'errors_24h', (select count(*) from public.client_errors where at > now() - interval '24 hours'),
    'errors_7d', (select count(*) from public.client_errors where at > now() - interval '7 days'),
    'top_errors', coalesce((select jsonb_agg(e) from (
        select message, count(*) n, max(at) last_at, max(version) version, max(screen) screen, count(distinct user_id) users
          from public.client_errors where at > now() - interval '7 days'
         group by message order by count(*) desc limit 10) e), '[]'::jsonb),
    'notify_calls', calls, 'notify_failed', bad_calls, 'push_ok', push_ok, 'push_bad', push_bad,
    'cron', coalesce((select jsonb_agg(j order by j->>'job') from (
        select jsonb_build_object('job', jb.jobname, 'schedule', jb.schedule, 'active', jb.active,
               'last', (select jsonb_build_object('status', d.status, 'at', d.start_time, 'msg', left(d.return_message, 140))
                          from cron.job_run_details d where d.jobid = jb.jobid order by d.start_time desc limit 1),
               'failed_24h', (select count(*) from cron.job_run_details d where d.jobid = jb.jobid and d.status = 'failed' and d.start_time > now() - interval '24 hours')) j
          from cron.job jb) s), '[]'::jsonb),
    'counts', jsonb_build_object(
        'users', (select count(*) from public.profiles),
        'push_users', (select count(distinct user_id) from public.push_subs),
        'groups', (select count(*) from public.groups),
        'posts_7d', (select count(*) from public.posts where created_at > now() - interval '7 days'),
        'messages_7d', (select count(*) from public.messages where created_at > now() - interval '7 days'),
        'reports_open', (select count(*) from public.reports where status = 'open'),
        'appeals_open', (select count(*) from public.sanction_appeals where status = 'open'),
        'timeouts_active', (select count(*) from public.moderation_timeouts where lifted_at is null and ends_at > now()))
  );
  return out;
end $$;
revoke all on function public.app_health() from public, anon;
grant execute on function public.app_health() to authenticated;

