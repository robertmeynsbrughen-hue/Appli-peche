-- 1. Groupe « Bienvenue » : chaque nouveau compte y entre automatiquement
-- ---------------------------------------------------------------------------
alter table public.groups add column if not exists is_welcome boolean not null default false;
create unique index if not exists groups_one_welcome on public.groups (is_welcome) where is_welcome;

-- le groupe Bienvenue n'a pas de limite de membres
create or replace function public.group_is_full(g bigint)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select not coalesce((select is_welcome from public.groups where id = g), false)
     and (select count(*) from public.memberships where group_id = g) >= 20;
$$;

do $$
declare g bigint; owner uuid;
begin
  select id into g from public.groups where is_welcome;
  if g is null then
    insert into public.groups (name, region, invite_code, require_approval, post_approval, is_welcome)
    values ('Bienvenue', null, 'bienvenue-' || substr(md5(random()::text), 1, 10), false, false, true)
    returning id into g;
  end if;
  select id into owner from public.profiles where is_admin order by created_at nulls last limit 1;
  if owner is not null then
    insert into public.memberships (group_id, user_id, role, status)
    values (g, owner, 'owner', 'active')
    on conflict (group_id, user_id) do update set role = 'owner', status = 'active';
  end if;
  -- les comptes déjà créés rejoignent aussi le groupe
  insert into public.memberships (group_id, user_id, role, status)
  select g, p.id, 'member', 'active' from public.profiles p
  on conflict do nothing;
end $$;

create or replace function public.join_welcome_group()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
declare g bigint;
begin
  select id into g from public.groups where is_welcome;
  if g is not null then
    insert into public.memberships (group_id, user_id, role, status)
    values (g, new.id, 'member', 'active')
    on conflict do nothing;
  end if;
  return new;
end $$;
revoke all on function public.join_welcome_group() from public, anon, authenticated;
drop trigger if exists profiles_welcome on public.profiles;
create trigger profiles_welcome after insert on public.profiles
  for each row execute function public.join_welcome_group();

