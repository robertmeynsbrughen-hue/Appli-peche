create table if not exists public.moderation_log (
  id          bigint generated by default as identity primary key,
  at          timestamptz not null default now(),
  actor       uuid references public.profiles(id) on delete set null,
  action      text not null,
  target_user uuid references public.profiles(id) on delete set null,
  group_id    bigint references public.groups(id) on delete set null,
  details     text
);
create index if not exists moderation_log_at_idx on public.moderation_log (at desc);
create index if not exists moderation_log_target_idx on public.moderation_log (target_user, at desc);
alter table public.moderation_log enable row level security;
drop policy if exists moderation_log_select on public.moderation_log;
create policy moderation_log_select on public.moderation_log for select to authenticated
  using (public.is_staff() or (group_id is not null and public.is_mod_of(group_id)));
-- aucune écriture directe : seuls les déclencheurs et fonctions ci-dessous écrivent

create or replace function public.modlog(p_action text, p_target uuid, p_group bigint, p_details text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if coalesce(current_setting('app.group_deletion', true), '') = 'on' and p_action <> 'delete_group' then return; end if;
  insert into public.moderation_log (actor, action, target_user, group_id, details)
  values (auth.uid(), p_action, p_target,
          case when p_group is not null and exists (select 1 from public.groups where id = p_group) then p_group end,
          left(p_details, 300));
end $$;
revoke all on function public.modlog(text, uuid, bigint, text) from public, anon, authenticated;

create or replace function public.modlog_trigger()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
declare me uuid := auth.uid(); g bigint;
begin
  if me is null then return coalesce(new, old); end if;   -- tâches automatiques : rien à journaliser
  if TG_TABLE_NAME = 'posts' then
    if TG_OP = 'UPDATE' and old.status = 'pending' and new.status = 'published' and new.user_id <> me then
      perform public.modlog('approve_post', new.user_id, new.group_id, coalesce(new.species, left(new.caption, 80)));
    elsif TG_OP = 'DELETE' and old.user_id <> me then
      perform public.modlog(case when old.status = 'pending' then 'reject_post' else 'delete_post' end, old.user_id, old.group_id, coalesce(old.species, left(old.caption, 80)));
    end if;
  elsif TG_TABLE_NAME = 'comments' then
    if old.user_id <> me then
      select group_id into g from public.posts where id = old.post_id;
      perform public.modlog('delete_comment', old.user_id, g, left(old.body, 120));
    end if;
  elsif TG_TABLE_NAME = 'messages' then
    if old.user_id <> me then
      perform public.modlog('delete_message', old.user_id, old.group_id, coalesce(left(old.body, 120), case when old.audio_path is not null then 'message vocal' else 'photo' end));
    end if;
  elsif TG_TABLE_NAME = 'memberships' then
    if TG_OP = 'UPDATE' and new.user_id <> me then
      if old.status = 'pending' and new.status = 'active' then perform public.modlog('approve_member', new.user_id, new.group_id, null);
      elsif old.role is distinct from new.role then perform public.modlog('role_change', new.user_id, new.group_id, old.role || ' → ' || new.role);
      end if;
    elsif TG_OP = 'DELETE' and old.user_id <> me then
      perform public.modlog(case when old.status = 'pending' then 'refuse_member' else 'remove_member' end, old.user_id, old.group_id, null);
    end if;
  elsif TG_TABLE_NAME = 'moderation_timeouts' then
    if TG_OP = 'INSERT' then
      perform public.modlog('timeout', new.user_id, null,
        case (extract(epoch from new.ends_at - new.starts_at) / 60)::int when 10 then '10 min' when 60 then '1 h' when 1440 then '24 h' when 10080 then '7 j' else ((extract(epoch from new.ends_at - new.starts_at) / 60)::int)::text || ' min' end || ' · ' || new.reason);
    elsif old.lifted_at is null and new.lifted_at is not null and coalesce(new.lift_reason, '') <> 'Remplacé par une nouvelle sanction' then
      perform public.modlog('lift_timeout', new.user_id, null, new.lift_reason);
    end if;
  elsif TG_TABLE_NAME = 'reports' then
    if old.status is distinct from new.status then
      perform public.modlog('report_' || coalesce(new.status, 'traite'), new.author_id, new.group_id, left(coalesce(new.reason, '') || coalesce(' « ' || new.excerpt || ' »', ''), 200));
    end if;
  elsif TG_TABLE_NAME = 'sanction_appeals' then
    if old.status is distinct from new.status then
      perform public.modlog('appeal_' || new.status, new.user_id, null, left(new.reply, 200));
    end if;
  elsif TG_TABLE_NAME = 'profiles' then
    if old.is_controller is distinct from new.is_controller then
      perform public.modlog(case when new.is_controller then 'controller_on' else 'controller_off' end, new.id, null, null);
    end if;
  elsif TG_TABLE_NAME = 'groups' then
    perform public.modlog('delete_group', null, null, old.name);
  end if;
  return coalesce(new, old);
end $$;
revoke all on function public.modlog_trigger() from public, anon, authenticated;

