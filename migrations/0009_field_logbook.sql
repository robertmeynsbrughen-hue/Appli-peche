-- 0009 : carnet de sortie utilisable hors réseau
--
-- Un membre note une sortie, ses prises et ses notes depuis le bord de l'eau,
-- même sans connexion. L'application garde la sortie sur le téléphone, puis
-- l'envoie au retour du réseau. Chaque sortie porte un identifiant créé par le
-- téléphone (client_id) : renvoyer la même sortie ne crée jamais de doublon.
--
-- Règles :
--   * le carnet est personnel : chaque membre ne voit que ses sorties ;
--   * les écritures passent uniquement par sync_logbook_outing() et
--     delete_logbook_outing() : aucune policy INSERT/UPDATE/DELETE directe ;
--   * une sortie contient au plus 50 prises ; les tailles et poids hors
--     limites sont ramenés dans une plage raisonnable au lieu d'être refusés ;
--   * le remplacement des prises est complet à chaque envoi, ce qui permet
--     d'ajouter, modifier ou supprimer une prise hors ligne sans conflit.
--
-- Migration rejouable sans erreur (conforme à migrations/README.md).
-- À appliquer séparément, hors déploiement automatique.

begin;

-- ---------------------------------------------------------------------------
-- 1. Sorties du carnet
-- ---------------------------------------------------------------------------

create table if not exists public.logbook_outings (
  id           bigint generated by default as identity primary key,
  client_id    uuid not null,
  user_id      uuid not null,
  occurred_at  timestamptz not null default now(),
  place        text,
  conditions   text,
  notes        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint logbook_outings_user_fkey
    foreign key (user_id) references public.profiles(id) on delete cascade,
  constraint logbook_outings_client_key unique (user_id, client_id),
  constraint logbook_outings_place_len
    check (place is null or char_length(place) <= 160),
  constraint logbook_outings_conditions_len
    check (conditions is null or char_length(conditions) <= 200),
  constraint logbook_outings_notes_len
    check (notes is null or char_length(notes) <= 4000)
);

comment on table public.logbook_outings is
  'Carnet de sortie personnel : une sortie, son lieu, ses conditions et ses notes.';

create index if not exists logbook_outings_user_date_idx
  on public.logbook_outings (user_id, occurred_at desc);

alter table public.logbook_outings enable row level security;

drop policy if exists logbook_outings_select on public.logbook_outings;
create policy logbook_outings_select on public.logbook_outings
  for select to authenticated
  using (user_id = auth.uid());

-- Aucune écriture directe : passer par les fonctions ci-dessous.
revoke all on public.logbook_outings from anon;
revoke insert, update, delete on public.logbook_outings from authenticated;
grant select on public.logbook_outings to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. Prises d'une sortie
-- ---------------------------------------------------------------------------

create table if not exists public.logbook_catches (
  id          bigint generated by default as identity primary key,
  outing_id   bigint not null,
  user_id     uuid not null,
  position    integer not null default 0,
  species     text,
  length_cm   numeric(5,1),
  weight_kg   numeric(6,2),
  bait        text,
  note        text,
  released    boolean,
  created_at  timestamptz not null default now(),
  constraint logbook_catches_outing_fkey
    foreign key (outing_id) references public.logbook_outings(id) on delete cascade,
  constraint logbook_catches_user_fkey
    foreign key (user_id) references public.profiles(id) on delete cascade,
  constraint logbook_catches_species_len
    check (species is null or char_length(species) <= 80),
  constraint logbook_catches_bait_len
    check (bait is null or char_length(bait) <= 120),
  constraint logbook_catches_note_len
    check (note is null or char_length(note) <= 500),
  constraint logbook_catches_length_range
    check (length_cm is null or (length_cm > 0 and length_cm <= 300)),
  constraint logbook_catches_weight_range
    check (weight_kg is null or (weight_kg > 0 and weight_kg <= 500))
);

comment on table public.logbook_catches is
  'Prises rattachées à une sortie du carnet personnel.';

create index if not exists logbook_catches_outing_idx
  on public.logbook_catches (outing_id, position);

alter table public.logbook_catches enable row level security;

drop policy if exists logbook_catches_select on public.logbook_catches;
create policy logbook_catches_select on public.logbook_catches
  for select to authenticated
  using (user_id = auth.uid());

revoke all on public.logbook_catches from anon;
revoke insert, update, delete on public.logbook_catches from authenticated;
grant select on public.logbook_catches to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. Envoyer une sortie (création ou mise à jour idempotente)
-- ---------------------------------------------------------------------------

create or replace function public.sync_logbook_outing(
  p_client_id uuid,
  p_payload jsonb
)
returns public.logbook_outings
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid      uuid := auth.uid();
  v_outing   public.logbook_outings%rowtype;
  v_catches  jsonb;
  v_when     timestamptz;
  v_place    text;
  v_cond     text;
  v_notes    text;
begin
  if v_uid is null then raise exception 'authentification requise'; end if;
  if p_client_id is null then raise exception 'identifiant de sortie manquant'; end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'sortie invalide';
  end if;

  v_place := nullif(btrim(left(coalesce(p_payload->>'place', ''), 160)), '');
  v_cond  := nullif(btrim(left(coalesce(p_payload->>'conditions', ''), 200)), '');
  v_notes := nullif(btrim(left(coalesce(p_payload->>'notes', ''), 4000)), '');

  begin
    v_when := coalesce(nullif(btrim(p_payload->>'occurred_at'), '')::timestamptz, now());
  exception when others then
    raise exception 'date de sortie invalide';
  end;

  insert into public.logbook_outings (client_id, user_id, occurred_at, place, conditions, notes)
  values (p_client_id, v_uid, v_when, v_place, v_cond, v_notes)
  on conflict (user_id, client_id) do update
    set occurred_at = excluded.occurred_at,
        place       = excluded.place,
        conditions  = excluded.conditions,
        notes       = excluded.notes,
        updated_at  = now()
  returning * into v_outing;

  -- Remplacement complet des prises : l'état envoyé fait foi.
  delete from public.logbook_catches
   where outing_id = v_outing.id and user_id = v_uid;

  v_catches := case
    when jsonb_typeof(p_payload->'catches') = 'array' then p_payload->'catches'
    else '[]'::jsonb
  end;

  if jsonb_array_length(v_catches) > 50 then
    raise exception 'trop de prises (50 maximum)';
  end if;

  insert into public.logbook_catches
    (outing_id, user_id, position, species, length_cm, weight_kg, bait, note, released)
  select
    v_outing.id,
    v_uid,
    (c.ord - 1)::integer,
    nullif(btrim(left(coalesce(c.j->>'species', ''), 80)), ''),
    case when coalesce(c.j->>'length_cm', '') ~ '^[0-9]{1,3}(\.[0-9]{1,2})?$'
         then least(greatest((c.j->>'length_cm')::numeric, 0.1), 300) end,
    case when coalesce(c.j->>'weight_kg', '') ~ '^[0-9]{1,3}(\.[0-9]{1,2})?$'
         then least(greatest((c.j->>'weight_kg')::numeric, 0.01), 500) end,
    nullif(btrim(left(coalesce(c.j->>'bait', ''), 120)), ''),
    nullif(btrim(left(coalesce(c.j->>'note', ''), 500)), ''),
    case when jsonb_typeof(c.j->'released') = 'boolean' then (c.j->>'released')::boolean end
  from jsonb_array_elements(v_catches) with ordinality as c(j, ord)
  where c.ord <= 50
    and (
      coalesce(btrim(c.j->>'species'), '') <> ''
      or coalesce(btrim(c.j->>'bait'), '') <> ''
      or coalesce(btrim(c.j->>'note'), '') <> ''
      or coalesce(c.j->>'length_cm', '') <> ''
      or coalesce(c.j->>'weight_kg', '') <> ''
    );

  return v_outing;
end;
$$;

revoke execute on function public.sync_logbook_outing(uuid, jsonb) from public, anon;
grant execute on function public.sync_logbook_outing(uuid, jsonb) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 4. Supprimer une sortie
-- ---------------------------------------------------------------------------

create or replace function public.delete_logbook_outing(p_client_id uuid)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_deleted integer := 0;
begin
  if auth.uid() is null then raise exception 'authentification requise'; end if;
  if p_client_id is null then raise exception 'identifiant de sortie manquant'; end if;

  delete from public.logbook_outings
   where user_id = auth.uid() and client_id = p_client_id;

  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

revoke execute on function public.delete_logbook_outing(uuid) from public, anon;
grant execute on function public.delete_logbook_outing(uuid) to authenticated, service_role;

