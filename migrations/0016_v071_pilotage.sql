-- au plus 10 signalements par jour et par compte
create or replace function public.bug_reports_limit()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if (select count(*) from public.bug_reports where user_id = new.user_id and created_at > now() - interval '1 day') >= 10 then
    raise exception 'trop de signalements aujourd''hui, merci !';
  end if;
  return new;
end $$;
drop trigger if exists bug_reports_limit on public.bug_reports;
create trigger bug_reports_limit before insert on public.bug_reports for each row execute function public.bug_reports_limit();
-- le développeur est prévenu dans son centre de notifications
create or replace function public.bug_reports_alert()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into public.notifications (user_id, title, body, url, tag)
  select p.id, '🐞 Bug signalé par @' || coalesce((select username from public.profiles where id = new.user_id), '?'),
         left(new.body, 300), './#profil?mod=bugs', 'bug-' || new.id
    from public.profiles p where p.is_admin;
  return new;
end $$;
revoke all on function public.bug_reports_alert() from public, anon, authenticated;
drop trigger if exists bug_reports_notify on public.bug_reports;
create trigger bug_reports_notify after insert on public.bug_reports for each row execute function public.bug_reports_alert();

