-- ---------------------------------------------------------------------------
-- 2. Sauvegardes : toutes les tables, 8 semaines, consultables par le développeur
-- ---------------------------------------------------------------------------
create schema if not exists backup;
create table if not exists backup.snapshots (
  id   bigint generated by default as identity primary key,
  snap date not null,
  tbl  text not null,
  data jsonb not null
);
create index if not exists snapshots_snap_idx on backup.snapshots (snap, tbl);
revoke all on schema backup from public, anon, authenticated;
revoke all on all tables in schema backup from public, anon, authenticated;

create or replace function backup.weekly()
returns void language plpgsql security definer set search_path = public, backup as $$
declare t text;
begin
  delete from backup.snapshots where snap = current_date or snap < current_date - 56;
  for t in
    select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r'
       and c.relname not in ('live_positions', 'invite_attempts', 'client_errors', 'notifications', 'push_subs', 'usage_days')
     order by c.relname
  loop
    execute format('insert into backup.snapshots (snap, tbl, data) select current_date, %L, to_jsonb(x) from public.%I x', t, t);
  end loop;
end $$;
revoke all on function backup.weekly() from public, anon, authenticated;

do $$
begin
  perform cron.unschedule(jobid) from cron.job where jobname = 'cdj-sauvegarde';
  perform cron.schedule('cdj-sauvegarde', '15 3 * * 0', 'select backup.weekly()');
end $$;

create or replace function public.backup_list()
returns table (snap date, tables int, rows bigint)
language plpgsql stable security definer set search_path = public, backup as $$
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  return query select s.snap, count(distinct s.tbl)::int, count(*) from backup.snapshots s group by s.snap order by s.snap desc;
end $$;
revoke all on function public.backup_list() from public, anon;
grant execute on function public.backup_list() to authenticated;

create or replace function public.backup_export(p_snap date)
returns jsonb language plpgsql stable security definer set search_path = public, backup as $$
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  return (select coalesce(jsonb_object_agg(tbl, rows), '{}'::jsonb)
            from (select tbl, jsonb_agg(data) rows from backup.snapshots where snap = p_snap group by tbl) x);
end $$;
revoke all on function public.backup_export(date) from public, anon;
grant execute on function public.backup_export(date) to authenticated;

create or replace function public.backup_now()
returns void language plpgsql security definer set search_path = public, backup as $$
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  perform backup.weekly();
end $$;
revoke all on function public.backup_now() from public, anon;
grant execute on function public.backup_now() to authenticated;

