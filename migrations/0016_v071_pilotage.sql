-- ---------------------------------------------------------------------------
-- 4. Statistiques d'usage (écrans ouverts, par jour et par compte)
-- ---------------------------------------------------------------------------
create table if not exists public.usage_days (
  user_id uuid not null references public.profiles(id) on delete cascade,
  day     date not null default (now() at time zone 'Europe/Paris')::date,
  screens jsonb not null default '{}'::jsonb,
  primary key (user_id, day)
);
alter table public.usage_days enable row level security;   -- aucun accès direct

create or replace function public.track_screen(p_screen text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare s text := left(regexp_replace(coalesce(p_screen, ''), '[^a-z0-9_-]', '', 'g'), 20);
begin
  if auth.uid() is null or s = '' then return; end if;
  if not exists (select 1 from public.profiles where id = auth.uid()) then return; end if;
  insert into public.usage_days (user_id, day, screens)
  values (auth.uid(), (now() at time zone 'Europe/Paris')::date, jsonb_build_object(s, 1))
  on conflict (user_id, day) do update
    set screens = usage_days.screens || jsonb_build_object(s, coalesce((usage_days.screens->>s)::int, 0) + 1)
    where (select count(*) from jsonb_object_keys(usage_days.screens)) < 40;
end $$;
revoke all on function public.track_screen(text) from public, anon;
grant execute on function public.track_screen(text) to authenticated;

create or replace function public.usage_stats()
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare today date := (now() at time zone 'Europe/Paris')::date;
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  return jsonb_build_object(
    'daily', (select coalesce(jsonb_agg(jsonb_build_object('day', d::date, 'n', (select count(*) from public.usage_days u where u.day = d::date)) order by d), '[]')
                from generate_series(today - 29, today, interval '1 day') d),
    'dau', (select count(*) from public.usage_days where day = today),
    'wau', (select count(distinct user_id) from public.usage_days where day > today - 7),
    'mau', (select count(distinct user_id) from public.usage_days where day > today - 30),
    'users', (select count(*) from public.profiles),
    'new_7d', (select count(*) from public.profiles where created_at > now() - interval '7 days'),
    'retention', (select case when count(*) = 0 then null else round(100.0 * count(*) filter (where back) / count(*)) end
                    from (select p.user_id, exists (select 1 from public.usage_days c where c.user_id = p.user_id and c.day > today - 7) back
                            from (select distinct user_id from public.usage_days where day between today - 13 and today - 7) p) r),
    'screens', (select coalesce(jsonb_agg(jsonb_build_object('screen', k, 'n', n) order by n desc), '[]')
                  from (select k, sum(v::int) n from public.usage_days, jsonb_each_text(screens) e(k, v) where day > today - 7 group by k order by 2 desc limit 12) s)
  );
end $$;
revoke all on function public.usage_stats() from public, anon;
grant execute on function public.usage_stats() to authenticated;

-- ---------------------------------------------------------------------------
-- 5. Mes données : export complet de ce qui appartient au compte
-- ---------------------------------------------------------------------------
create or replace function public.export_my_data()
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare out jsonb; t text; rows jsonb; me uuid := auth.uid();
begin
  if me is null then raise exception 'non connecté'; end if;
  out := jsonb_build_object('exported_at', now(), 'profile', (select to_jsonb(p) from public.profiles p where p.id = me));
  for t in
    select c.table_name from information_schema.columns c join information_schema.tables tb using (table_schema, table_name)
     where c.table_schema = 'public' and c.column_name = 'user_id' and tb.table_type = 'BASE TABLE'
       and c.table_name not in ('push_subs', 'client_errors', 'usage_days')
     order by 1
  loop
    execute format('select jsonb_agg(to_jsonb(x)) from public.%I x where x.user_id = $1', t) into rows using me;
    if rows is not null then out := out || jsonb_build_object(t, rows); end if;
  end loop;
  out := out || jsonb_build_object('direct_messages_received',
    (select jsonb_agg(to_jsonb(d)) from public.direct_messages d where d.to_user = me));
  return out;
end $$;
revoke all on function public.export_my_data() from public, anon;
grant execute on function public.export_my_data() to authenticated;

