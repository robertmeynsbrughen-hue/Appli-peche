-- 6. Comptes inactifs depuis 2 ans : prévenus, puis supprimés par le développeur
-- ---------------------------------------------------------------------------
create or replace function public.last_activity(u uuid)
returns timestamptz language sql stable security definer set search_path = public, auth, pg_temp as $$
  select greatest(
    (select last_sign_in_at from auth.users where id = u),
    (select max(day)::timestamptz from public.usage_days where user_id = u),
    (select created_at from public.profiles where id = u));
$$;
revoke all on function public.last_activity(uuid) from public, anon, authenticated;

create or replace function public.inactive_accounts()
returns table (id uuid, username text, last_seen timestamptz, warned boolean)
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  return query
    select p.id, p.username, public.last_activity(p.id),
           exists (select 1 from public.notifications n where n.user_id = p.id and n.tag = 'inactif')
      from public.profiles p
     where not p.is_admin and public.last_activity(p.id) < now() - interval '23 months'
     order by 3;
end $$;
revoke all on function public.inactive_accounts() from public, anon;
grant execute on function public.inactive_accounts() to authenticated;

create or replace function public.warn_inactive()
returns int language plpgsql security definer set search_path = public, pg_temp as $$
declare n int;
begin
  insert into public.notifications (user_id, title, body, url, tag)
  select p.id, '👋 Tu nous manques !', 'Ton compte Rivio n''a pas servi depuis presque 2 ans. Sans connexion d''ici un mois, il pourra être supprimé avec ses données. Ouvre l''appli pour le garder.', './#profil', 'inactif'
    from public.profiles p
   where not p.is_admin and public.last_activity(p.id) < now() - interval '23 months'
     and not exists (select 1 from public.notifications n where n.user_id = p.id and n.tag = 'inactif');
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.warn_inactive() from public, anon, authenticated;
do $$
begin
  perform cron.unschedule(jobid) from cron.job where jobname = 'cdj-inactifs';
  perform cron.schedule('cdj-inactifs', '33 9 2 * *', 'select public.warn_inactive()');
end $$;

create or replace function public.admin_delete_inactive(p_user uuid)
returns void language plpgsql security definer set search_path = public, auth, backup, pg_temp as $$
declare u text := p_user::text; name text;
begin
  if not public.is_admin() then raise exception 'non autorisé'; end if;
  select username into name from public.profiles where id = p_user and not is_admin;
  if name is null then raise exception 'compte introuvable'; end if;
  if public.last_activity(p_user) > now() - interval '24 months' then raise exception 'ce compte a servi il y a moins de 2 ans'; end if;
  if not exists (select 1 from public.notifications where user_id = p_user and tag = 'inactif' and created_at < now() - interval '25 days') then
    raise exception 'le membre doit d''abord avoir été prévenu il y a au moins 25 jours';
  end if;
  perform public.modlog('delete_account', null, null, '@' || name || ' (inactif depuis 2 ans)');
  delete from backup.snapshots where data->>'user_id' = u or (tbl = 'profiles' and data->>'id' = u);
  delete from auth.users where id = p_user;
end $$;
revoke all on function public.admin_delete_inactive(uuid) from public, anon;
grant execute on function public.admin_delete_inactive(uuid) to authenticated;

