-- 0006 : sanctions temporaires globales (« timeout ») appliquées par le serveur
--
-- Objectif : un développeur ou un contrôleur peut suspendre temporairement un
-- compte depuis Profil > Modération. Pendant la sanction, le membre peut se
-- connecter et lire l'application, mais ne peut plus rien écrire : prises,
-- commentaires, messages de chat (texte, photo, vocal) et chat staff.
--
-- La sanction est vérifiée en base, pas seulement dans l'interface :
--   * triggers BEFORE INSERT sur posts / comments / messages / staff_messages ;
--   * policy de stockage restrictive sur le bucket photos, qui bloque aussi un
--     envoi de photo ou de vocal depuis un panneau de chat déjà ouvert.
--
-- Droits : seuls les développeurs et contrôleurs appliquent ou lèvent une
-- sanction. Un contrôleur ne peut pas suspendre un développeur ni un autre
-- contrôleur : c'est réservé au développeur.
--
-- Migration rejouable sans erreur (conforme à migrations/README.md).
-- À appliquer séparément, hors déploiement automatique.

begin;

-- ---------------------------------------------------------------------------
-- 1. Table des sanctions
-- ---------------------------------------------------------------------------

create table if not exists public.moderation_timeouts (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null,
  reason      text not null,
  starts_at   timestamptz not null default now(),
  ends_at     timestamptz not null,
  created_by  uuid,
  created_at  timestamptz not null default now(),
  lifted_at   timestamptz,
  lifted_by   uuid,
  lift_reason text,
  constraint moderation_timeouts_user_id_fkey
    foreign key (user_id) references public.profiles(id) on delete cascade,
  -- Un membre du staff peut supprimer son compte : on garde la trace de la
  -- sanction (et de sa levée) sans bloquer la suppression.
  constraint moderation_timeouts_created_by_fkey
    foreign key (created_by) references public.profiles(id) on delete set null,
  constraint moderation_timeouts_lifted_by_fkey
    foreign key (lifted_by) references public.profiles(id) on delete set null,
  constraint moderation_timeouts_reason_len
    check (char_length(btrim(reason)) between 3 and 300),
  constraint moderation_timeouts_span
    check (ends_at > starts_at)
);

comment on table public.moderation_timeouts is
  'Sanctions temporaires globales : qui, motif, début, fin, levée éventuelle.';

create index if not exists moderation_timeouts_user_active_idx
  on public.moderation_timeouts (user_id, ends_at desc)
  where lifted_at is null;

alter table public.moderation_timeouts enable row level security;

drop policy if exists moderation_timeouts_select on public.moderation_timeouts;
create policy moderation_timeouts_select on public.moderation_timeouts
  for select to authenticated
  using (user_id = auth.uid() or public.is_staff());

-- Aucune écriture directe : passer par apply_timeout() / lift_timeout().
revoke all on public.moderation_timeouts from anon;
revoke insert, update, delete on public.moderation_timeouts from authenticated;
grant select on public.moderation_timeouts to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. Lecture de la sanction active
-- ---------------------------------------------------------------------------

create or replace function public.is_timed_out()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.moderation_timeouts t
    where t.user_id = auth.uid()
      and t.lifted_at is null
      and t.ends_at > now()
  );
$$;

revoke execute on function public.is_timed_out() from public, anon;
grant execute on function public.is_timed_out() to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. Garde-fou serveur sur les écritures
-- ---------------------------------------------------------------------------

create or replace function public.enforce_timeout()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  t public.moderation_timeouts%rowtype;
begin
  -- service_role / migrations : pas de session utilisateur, on laisse passer.
  if auth.uid() is null then return new; end if;
  if new.user_id is distinct from auth.uid() then return new; end if;

  select * into t
  from public.moderation_timeouts
  where user_id = auth.uid()
    and lifted_at is null
    and ends_at > now()
  order by ends_at desc
  limit 1;

  if not found then return new; end if;

  raise exception
    'Compte suspendu jusqu''au % (heure de Paris). Motif : %',
    to_char(t.ends_at at time zone 'Europe/Paris', 'DD/MM/YYYY à HH24:MI'),
    t.reason
    using errcode = '42501';
end;
$$;

-- La fonction ne peut être appelée que par un trigger (elle renvoie trigger),
-- mais on laisse EXECUTE à authenticated : certains déploiements vérifient ce
-- droit au moment où le trigger se déclenche.
revoke execute on function public.enforce_timeout() from public, anon;
grant execute on function public.enforce_timeout() to authenticated;

drop trigger if exists timeout_guard on public.posts;
create trigger timeout_guard
  before insert on public.posts
  for each row execute function public.enforce_timeout();

drop trigger if exists timeout_guard on public.comments;
create trigger timeout_guard
  before insert on public.comments
  for each row execute function public.enforce_timeout();

drop trigger if exists timeout_guard on public.messages;
create trigger timeout_guard
  before insert on public.messages
  for each row execute function public.enforce_timeout();

drop trigger if exists timeout_guard on public.staff_messages;
create trigger timeout_guard
  before insert on public.staff_messages
  for each row execute function public.enforce_timeout();

-- Les photos et vocaux du chat passent par les buckets « photos » (groupe) et
-- « staff-media » (chat staff) avant l'insert. Une policy restrictive s'ajoute
-- (ET logique) aux policies existantes.
drop policy if exists timeout_photos_upload on storage.objects;
create policy timeout_photos_upload on storage.objects
  as restrictive
  for insert
  to authenticated
  with check (bucket_id not in ('photos', 'staff-media') or not public.is_timed_out());

-- ---------------------------------------------------------------------------
-- 4. Appliquer une sanction
-- ---------------------------------------------------------------------------

create or replace function public.apply_timeout(
  p_user uuid,
  p_minutes integer,
  p_reason text
)
returns public.moderation_timeouts
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_reason text := btrim(coalesce(p_reason, ''));
  v_target public.profiles%rowtype;
  v_row public.moderation_timeouts%rowtype;
begin
  if auth.uid() is null then raise exception 'authentification requise'; end if;
  if not public.is_staff() then raise exception 'non autorisé'; end if;
  if p_user is null then raise exception 'membre introuvable'; end if;
  if p_user = auth.uid() then raise exception 'tu ne peux pas te suspendre toi-même'; end if;
  if p_minutes is null or p_minutes not in (10, 60, 1440, 10080) then
    raise exception 'durée non autorisée (10 min, 1 h, 24 h ou 7 j)';
  end if;
  if char_length(v_reason) < 3 then
    raise exception 'motif obligatoire (3 caractères minimum)';
  end if;
  if char_length(v_reason) > 300 then
    raise exception 'motif trop long (300 caractères maximum)';
  end if;

  select * into v_target from public.profiles where id = p_user;
  if not found then raise exception 'membre introuvable'; end if;

  -- Un contrôleur ne touche pas au staff : seul le développeur le peut.
  if not public.is_admin() and (v_target.is_admin or v_target.is_controller) then
    raise exception 'seul le développeur peut suspendre un membre du staff';
  end if;

  -- Une seule sanction active à la fois : la précédente est clôturée.
  update public.moderation_timeouts
     set lifted_at = now(),
         lifted_by = auth.uid(),
         lift_reason = 'Remplacé par une nouvelle sanction'
   where user_id = p_user
     and lifted_at is null
     and ends_at > now();

  insert into public.moderation_timeouts (user_id, reason, starts_at, ends_at, created_by)
  values (p_user, v_reason, now(), now() + make_interval(mins => p_minutes), auth.uid())
  returning * into v_row;

  insert into public.notifications (user_id, title, body, url, tag)
  values (
    p_user,
    '⏳ Sanction temporaire',
    'Ton compte est suspendu jusqu''au '
      || to_char(v_row.ends_at at time zone 'Europe/Paris', 'DD/MM/YYYY à HH24:MI')
      || '. Motif : ' || v_reason,
    './#profil',
    'timeout-' || v_row.id
  );

  return v_row;
end;
$$;

revoke execute on function public.apply_timeout(uuid, integer, text) from public, anon;
grant execute on function public.apply_timeout(uuid, integer, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 5. Lever une sanction
-- ---------------------------------------------------------------------------

create or replace function public.lift_timeout(
  p_id bigint,
  p_reason text default null
)
returns public.moderation_timeouts
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_row public.moderation_timeouts%rowtype;
  v_target public.profiles%rowtype;
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if auth.uid() is null then raise exception 'authentification requise'; end if;
  if not public.is_staff() then raise exception 'non autorisé'; end if;

  select * into v_row from public.moderation_timeouts where id = p_id for update;
  if not found then raise exception 'sanction introuvable'; end if;
  if v_row.lifted_at is not null then raise exception 'sanction déjà levée'; end if;

  select * into v_target from public.profiles where id = v_row.user_id;

  if not public.is_admin() and (v_target.is_admin or v_target.is_controller) then
    raise exception 'seul le développeur peut lever la sanction d''un membre du staff';
  end if;

  update public.moderation_timeouts
     set lifted_at = now(),
         lifted_by = auth.uid(),
         lift_reason = coalesce(v_reason, 'Levée manuelle')
   where id = p_id
  returning * into v_row;

  insert into public.notifications (user_id, title, body, url, tag)
  values (
    v_row.user_id,
    '✅ Sanction levée',
    'Ta sanction temporaire a été levée'
      || case when v_reason is not null then ' (' || v_reason || ')' else '' end
      || '. Tu peux de nouveau publier.',
    './#profil',
    'timeout-lift-' || v_row.id
  );

  return v_row;
end;
$$;

revoke execute on function public.lift_timeout(bigint, text) from public, anon;
grant execute on function public.lift_timeout(bigint, text) to authenticated;

