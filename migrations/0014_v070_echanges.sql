alter table public.profiles add column if not exists mentor_available boolean not null default false;
create table if not exists public.mentorships (
  mentee     uuid primary key references public.profiles(id) on delete cascade,
  mentor     uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint mentorships_not_self check (mentee <> mentor)
);
alter table public.mentorships enable row level security;
drop policy if exists mentorships_select on public.mentorships;
create policy mentorships_select on public.mentorships for select to authenticated
  using (mentee = auth.uid() or mentor = auth.uid() or public.shares_group(mentee) or public.is_staff());
drop policy if exists mentorships_delete on public.mentorships;
create policy mentorships_delete on public.mentorships for delete to authenticated
  using (mentee = auth.uid() or mentor = auth.uid() or public.is_staff());

create or replace function public.set_mentor_available(p_on boolean)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null then raise exception 'non connecté'; end if;
  if p_on and public.is_timed_out() then raise exception 'compte suspendu : impossible pour le moment' using errcode = '42501'; end if;
  update public.profiles set mentor_available = coalesce(p_on, false) where id = auth.uid();
end $$;
revoke all on function public.set_mentor_available(boolean) from public, anon;
grant execute on function public.set_mentor_available(boolean) to authenticated;

-- volontaires disponibles (au plus 3 filleuls chacun)
create or replace function public.list_mentors()
returns table (id uuid, username text, fish_styles text[], bio text, mentees int)
language sql stable security definer set search_path = public, pg_temp as $$
  select p.id, p.username, p.fish_styles, p.bio, (select count(*)::int from public.mentorships m where m.mentor = p.id)
    from public.profiles p
   where p.mentor_available and p.id <> auth.uid() and auth.uid() is not null
     and (select count(*) from public.mentorships m where m.mentor = p.id) < 3
     and not exists (select 1 from public.moderation_timeouts t where t.user_id = p.id and t.lifted_at is null and t.ends_at > now())
   order by p.username;
$$;
revoke all on function public.list_mentors() from public, anon;
grant execute on function public.list_mentors() to authenticated;

create or replace function public.choose_mentor(p_mentor uuid)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null then raise exception 'non connecté'; end if;
  if exists (select 1 from public.mentorships where mentee = auth.uid()) then raise exception 'tu as déjà un parrain'; end if;
  if not exists (select 1 from public.list_mentors() l where l.id = p_mentor) then raise exception 'ce parrain n''est plus disponible'; end if;
  insert into public.mentorships (mentee, mentor) values (auth.uid(), p_mentor);
  perform public.call_notify(jsonb_build_object('table', 'mentorships', 'mentor', p_mentor, 'mentee', auth.uid()));
end $$;
revoke all on function public.choose_mentor(uuid) from public, anon;
grant execute on function public.choose_mentor(uuid) to authenticated;

