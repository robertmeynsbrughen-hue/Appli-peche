create or replace function public.group_month_stats(g bigint, p_month date)
returns jsonb language sql stable security definer set search_path = public, pg_temp as $$
  with b as (select date_trunc('month', p_month)::timestamptz s, (date_trunc('month', p_month) + interval '1 month')::timestamptz e),
  c as (
    select user_id, species, length_cm from public.posts, b where group_id = g and status = 'published' and created_at >= b.s and created_at < b.e
    union all
    select user_id, species, length_cm from public.sessions, b where group_id = g and caught is not false and species is not null and created_at >= b.s and created_at < b.e
  )
  select jsonb_build_object(
    'month', to_char(p_month, 'YYYY-MM-01'),
    'catches', (select count(*) from c),
    'species', (select count(distinct species) from c where species is not null),
    'anglers', (select count(distinct user_id) from c),
    'biggest', (select jsonb_build_object('username', p.username, 'species', c.species, 'length_cm', c.length_cm)
                  from c join public.profiles p on p.id = c.user_id where c.length_cm is not null order by c.length_cm desc limit 1),
    'top', (select jsonb_build_object('username', p.username, 'n', x.n) from (select user_id, count(*) n from c group by user_id order by count(*) desc limit 1) x join public.profiles p on p.id = x.user_id),
    'messages', (select count(*) from public.messages, b where group_id = g and created_at >= b.s and created_at < b.e)
  );
$$;
revoke all on function public.group_month_stats(bigint, date) from public, anon, authenticated;
grant execute on function public.group_month_stats(bigint, date) to service_role;

create or replace function public.my_group_month(p_group bigint, p_month date default null)
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if not (public.is_member_of(p_group) or public.is_staff()) then raise exception 'non autorisé'; end if;
  return public.group_month_stats(p_group, coalesce(p_month, (date_trunc('month', now() at time zone 'Europe/Paris') - interval '1 month')::date));
end $$;
revoke all on function public.my_group_month(bigint, date) from public, anon;
grant execute on function public.my_group_month(bigint, date) to authenticated;

