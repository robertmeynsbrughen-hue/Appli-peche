-- la réponse doit viser un message du même groupe
create or replace function public.check_reply_to()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.reply_to is not null and not exists (select 1 from public.messages where id = new.reply_to and group_id = new.group_id) then
    new.reply_to := null;
  end if;
  return new;
end $$;
revoke all on function public.check_reply_to() from public, anon, authenticated;
drop trigger if exists messages_reply_check on public.messages;
create trigger messages_reply_check before insert on public.messages for each row execute function public.check_reply_to();

create or replace function public.pin_message(p_id bigint, p_on boolean)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare g bigint;
begin
  select group_id into g from public.messages where id = p_id;
  if g is null then raise exception 'message introuvable'; end if;
  if not public.can_moderate(g) then raise exception 'non autorisé'; end if;
  if p_on then
    update public.messages set pinned_at = null, pinned_by = null where group_id = g and pinned_at is not null and id <> p_id;
    update public.messages set pinned_at = now(), pinned_by = auth.uid() where id = p_id;
  else
    update public.messages set pinned_at = null, pinned_by = null where id = p_id;
  end if;
end $$;
revoke all on function public.pin_message(bigint, boolean) from public, anon;
grant execute on function public.pin_message(bigint, boolean) to authenticated;

