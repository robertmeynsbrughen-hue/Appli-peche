-- liste des conversations : dernier message et non-lus
create or replace function public.dm_threads()
returns table (other uuid, username text, last_body text, last_at timestamptz, last_mine boolean, unread int)
language sql stable security definer set search_path = public, pg_temp as $$
  with mine as (
    select case when user_id = auth.uid() then to_user else user_id end as other, body, created_at, user_id = auth.uid() as is_mine, read_at, to_user
      from public.direct_messages where auth.uid() in (user_id, to_user)
  ), last as (
    select distinct on (other) other, body, created_at, is_mine from mine order by other, created_at desc
  )
  select l.other, p.username, left(l.body, 120), l.created_at, l.is_mine,
         (select count(*)::int from mine m where m.other = l.other and m.to_user = auth.uid() and m.read_at is null)
    from last l join public.profiles p on p.id = l.other
   order by l.created_at desc limit 50;
$$;
revoke all on function public.dm_threads() from public, anon;
grant execute on function public.dm_threads() to authenticated;

