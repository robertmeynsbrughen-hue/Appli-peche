-- meilleure réponse : choisie par l'auteur de la question ou un modérateur
create or replace function public.qa_set_best(p_question bigint, p_answer bigint)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare q public.qa_questions%rowtype;
begin
  select * into q from public.qa_questions where id = p_question;
  if not found then raise exception 'question introuvable'; end if;
  if not (q.user_id = auth.uid() or public.can_moderate(q.group_id)) then raise exception 'non autorisé'; end if;
  if p_answer is not null and not exists (select 1 from public.qa_answers where id = p_answer and question_id = p_question) then raise exception 'réponse introuvable'; end if;
  update public.qa_questions set best_answer_id = p_answer where id = p_question;
end $$;
revoke all on function public.qa_set_best(bigint, bigint) from public, anon;
grant execute on function public.qa_set_best(bigint, bigint) to authenticated;

