create table if not exists public.direct_messages (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references public.profiles(id) on delete cascade,  -- expéditeur
  to_user    uuid not null references public.profiles(id) on delete cascade,
  body       text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now(),
  read_at    timestamptz,
  constraint direct_messages_not_self check (user_id <> to_user)
);
create index if not exists direct_messages_pair_idx on public.direct_messages (least(user_id, to_user), greatest(user_id, to_user), created_at desc);
create index if not exists direct_messages_unread_idx on public.direct_messages (to_user) where read_at is null;
alter table public.direct_messages enable row level security;

create table if not exists public.dm_blocks (
  user_id    uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  blocked    uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, blocked)
);
alter table public.dm_blocks enable row level security;
drop policy if exists dm_blocks_own on public.dm_blocks;
create policy dm_blocks_own on public.dm_blocks for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create or replace function public.dm_allowed(p_to uuid)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select auth.uid() is not null and p_to <> auth.uid()
     and (public.shares_group(p_to) or public.is_staff())
     and not exists (select 1 from public.dm_blocks where user_id = p_to and blocked = auth.uid());
$$;
grant execute on function public.dm_allowed(uuid) to authenticated;

drop policy if exists direct_messages_select on public.direct_messages;
create policy direct_messages_select on public.direct_messages for select to authenticated
  using (user_id = auth.uid() or to_user = auth.uid());
drop policy if exists direct_messages_insert on public.direct_messages;
create policy direct_messages_insert on public.direct_messages for insert to authenticated
  with check (user_id = auth.uid() and public.dm_allowed(to_user));
drop policy if exists direct_messages_delete on public.direct_messages;
create policy direct_messages_delete on public.direct_messages for delete to authenticated
  using (user_id = auth.uid());
revoke update on public.direct_messages from authenticated;
drop trigger if exists timeout_guard on public.direct_messages;
