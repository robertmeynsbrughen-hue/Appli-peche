-- 0008 : recours contre une sanction temporaire
--
-- Un membre suspendu peut demander un réexamen depuis son profil. Il garde la
-- lecture de l'application, mais son droit d'écrire reste bloqué pendant tout
-- l'examen : le recours ne lève jamais la sanction automatiquement.
--
-- Le recours apparaît dans la console de modération. Un développeur ou un
-- contrôleur y répond, puis choisit de maintenir ou de lever la sanction. La
-- décision et la réponse sont notifiées au membre.
--
-- Règles :
--   * un seul recours par sanction (timeout_id unique) ;
--   * message obligatoire (10 à 1000 caractères), réponse du staff obligatoire ;
--   * écritures uniquement par les fonctions submit_sanction_appeal() et
--     respond_sanction_appeal() : aucune policy INSERT/UPDATE directe ;
--   * un membre ne peut pas traiter son propre recours ;
--   * seul un développeur peut traiter le recours d'un membre du staff.
--
-- Migration rejouable sans erreur (conforme à migrations/README.md).
-- À appliquer séparément, hors déploiement automatique.

begin;

-- La table des sanctions vient de 0006 : message clair si elle manque.
do $$
begin
  if to_regclass('public.moderation_timeouts') is null then
    raise exception
      '0008 nécessite la migration 0006_timeouts.sql (table public.moderation_timeouts absente)';
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- 1. Table des recours
-- ---------------------------------------------------------------------------

create table if not exists public.sanction_appeals (
  id          bigint generated by default as identity primary key,
  timeout_id  bigint not null,
  user_id     uuid not null,
  message     text not null,
  status      text not null default 'open',
  reply       text,
  created_at  timestamptz not null default now(),
  handled_at  timestamptz,
  handled_by  uuid,
  constraint sanction_appeals_timeout_fkey
    foreign key (timeout_id) references public.moderation_timeouts(id) on delete cascade,
  constraint sanction_appeals_user_fkey
    foreign key (user_id) references public.profiles(id) on delete cascade,
  constraint sanction_appeals_handled_by_fkey
    foreign key (handled_by) references public.profiles(id) on delete set null,
  constraint sanction_appeals_timeout_key unique (timeout_id),
  constraint sanction_appeals_status_check
    check (status in ('open', 'accepted', 'rejected')),
  constraint sanction_appeals_message_len
    check (char_length(btrim(message)) between 10 and 1000),
  constraint sanction_appeals_reply_len
    check (reply is null or char_length(btrim(reply)) between 3 and 1000),
  constraint sanction_appeals_handled_check
    check ((status = 'open' and handled_at is null and handled_by is null and reply is null)
        or (status <> 'open' and handled_at is not null and handled_by is not null and reply is not null))
);

comment on table public.sanction_appeals is
  'Recours d''un membre suspendu : demande, décision du staff et réponse.';

create index if not exists sanction_appeals_status_idx
  on public.sanction_appeals (status, created_at desc);

create index if not exists sanction_appeals_user_idx
  on public.sanction_appeals (user_id, created_at desc);

alter table public.sanction_appeals enable row level security;

-- Le membre voit ses recours, le staff voit tous les recours.
drop policy if exists sanction_appeals_select on public.sanction_appeals;
create policy sanction_appeals_select on public.sanction_appeals
  for select to authenticated
  using (user_id = auth.uid() or public.is_staff());

-- Aucune écriture directe : passer par les fonctions ci-dessous.
revoke all on public.sanction_appeals from anon;
revoke insert, update, delete on public.sanction_appeals from authenticated;
grant select on public.sanction_appeals to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. Envoyer un recours (membre suspendu)
-- ---------------------------------------------------------------------------

create or replace function public.submit_sanction_appeal(
  p_timeout_id bigint,
  p_message text
)
returns public.sanction_appeals
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_msg text := btrim(coalesce(p_message, ''));
  v_username text;
  v_timeout public.moderation_timeouts%rowtype;
  v_row public.sanction_appeals%rowtype;
begin
  if auth.uid() is null then raise exception 'authentification requise'; end if;
  if p_timeout_id is null then raise exception 'sanction introuvable'; end if;

  select * into v_timeout
  from public.moderation_timeouts
  where id = p_timeout_id
  for update;

  if not found then raise exception 'sanction introuvable'; end if;
  if v_timeout.user_id <> auth.uid() then raise exception 'non autorisé'; end if;
  if v_timeout.lifted_at is not null then
    raise exception 'cette sanction a déjà été levée';
  end if;
  if v_timeout.ends_at <= now() then
    raise exception 'cette sanction est déjà terminée';
  end if;

  if char_length(v_msg) < 10 then
    raise exception 'explique ta demande (10 caractères minimum)';
  end if;
  if char_length(v_msg) > 1000 then
    raise exception 'message trop long (1000 caractères maximum)';
  end if;

  begin
    insert into public.sanction_appeals (timeout_id, user_id, message)
    values (p_timeout_id, auth.uid(), v_msg)
    returning * into v_row;
  exception when unique_violation then
    raise exception 'tu as déjà envoyé un recours pour cette sanction';
  end;

  select username into v_username from public.profiles where id = auth.uid();

  -- Accusé de réception au membre.
  insert into public.notifications (user_id, title, body, url, tag)
  values (
    auth.uid(),
    '📨 Recours envoyé',
    'Ta demande de réexamen a bien été transmise au staff. La sanction reste active pendant l''examen.',
    './#profil?appeal=1',
    'appeal-' || v_row.id
  );

  -- Le staff est prévenu (sauf le membre lui-même s'il est du staff).
  insert into public.notifications (user_id, title, body, url, tag)
  select p.id,
         '📨 Recours à examiner',
         '@' || coalesce(v_username, 'un membre') || ' demande un réexamen de sa sanction.',
         './#profil?mod=appeals',
         'appeal-staff-' || v_row.id
  from public.profiles p
  where (p.is_admin or p.is_controller)
    and p.id <> auth.uid();

  return v_row;
end;
$$;

revoke execute on function public.submit_sanction_appeal(bigint, text) from public, anon;
grant execute on function public.submit_sanction_appeal(bigint, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. Répondre à un recours (staff)
-- ---------------------------------------------------------------------------

create or replace function public.respond_sanction_appeal(
  p_id bigint,
  p_accept boolean,
  p_reply text
)
returns public.sanction_appeals
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_row public.sanction_appeals%rowtype;
  v_timeout public.moderation_timeouts%rowtype;
  v_target public.profiles%rowtype;
  v_reply text := btrim(coalesce(p_reply, ''));
begin
  if auth.uid() is null then raise exception 'authentification requise'; end if;
  if not public.is_staff() then raise exception 'non autorisé'; end if;
  if p_id is null then raise exception 'recours introuvable'; end if;
  if p_accept is null then raise exception 'décision manquante'; end if;

  if char_length(v_reply) < 3 then
    raise exception 'réponse obligatoire (3 caractères minimum)';
  end if;
  if char_length(v_reply) > 1000 then
    raise exception 'réponse trop longue (1000 caractères maximum)';
  end if;

  select * into v_row
  from public.sanction_appeals
  where id = p_id
  for update;

  if not found then raise exception 'recours introuvable'; end if;
  if v_row.status <> 'open' then raise exception 'ce recours a déjà été traité'; end if;
  if v_row.user_id = auth.uid() then
    raise exception 'tu ne peux pas traiter ton propre recours';
  end if;

  select * into v_timeout
  from public.moderation_timeouts
  where id = v_row.timeout_id
  for update;

  if not found then raise exception 'sanction introuvable'; end if;

  select * into v_target from public.profiles where id = v_row.user_id;

  -- Un contrôleur ne traite pas le recours d'un membre du staff.
  if not public.is_admin() and (v_target.is_admin or v_target.is_controller) then
    raise exception 'seul le développeur peut traiter le recours d''un membre du staff';
  end if;

  if p_accept then
    if v_timeout.lifted_at is not null then
      raise exception 'cette sanction a déjà été levée';
    end if;
    if v_timeout.ends_at <= now() then
      raise exception 'cette sanction est déjà terminée';
    end if;

    update public.moderation_timeouts
       set lifted_at = now(),
           lifted_by = auth.uid(),
           lift_reason = left('Recours accepté : ' || v_reply, 300)
     where id = v_timeout.id
    returning * into v_timeout;
  end if;

  update public.sanction_appeals
     set status = case when p_accept then 'accepted' else 'rejected' end,
         reply = v_reply,
         handled_at = now(),
         handled_by = auth.uid()
   where id = p_id
  returning * into v_row;

  insert into public.notifications (user_id, title, body, url, tag)
  values (
    v_row.user_id,
    case when p_accept then '✅ Recours accepté' else '📩 Recours examiné' end,
    case when p_accept
      then 'Ta sanction a été levée. Réponse du staff : '
      else 'Ta sanction est maintenue. Réponse du staff : '
    end || left(v_reply, 400),
    './#profil?appeal=1',
    'appeal-reply-' || v_row.id
  );

  return v_row;
end;
$$;

revoke execute on function public.respond_sanction_appeal(bigint, boolean, text) from public, anon;
grant execute on function public.respond_sanction_appeal(bigint, boolean, text) to authenticated, service_role;

